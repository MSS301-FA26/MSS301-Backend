-- Identity-owned transactional outbox. No dependency on Payment's database.
CREATE TABLE outbox_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(128) NOT NULL UNIQUE,
    aggregate_type VARCHAR(50) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    retry_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMP WITHOUT TIME ZONE,
    next_attempt_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_identity_outbox_activation UNIQUE (aggregate_type, aggregate_id, event_type),
    CONSTRAINT ck_identity_outbox_status CHECK (status IN ('PENDING', 'PUBLISHED'))
);
CREATE INDEX idx_identity_outbox_pending ON outbox_events (next_attempt_at, id) WHERE status = 'PENDING';
