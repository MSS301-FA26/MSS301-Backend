-- ==============================================================================
-- PAYMENT SERVICE SCHEMA (Flyway V9 Migration)
-- Add payment_transactions, refund_batches, refunds tables
-- Extend payments and wallet_transactions tables
-- ==============================================================================

-- 1. Extend payments table
ALTER TABLE payments ADD COLUMN IF NOT EXISTS expires_at TIMESTAMP;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS remaining_refundable_amount NUMERIC(12,2);

-- Update existing payments to initialize remaining_refundable_amount
UPDATE payments SET remaining_refundable_amount = amount WHERE remaining_refundable_amount IS NULL;

-- 2. Create payment_transactions table for multi-attempt audit
CREATE TABLE IF NOT EXISTS payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(id) ON DELETE CASCADE,
    provider VARCHAR(30) NOT NULL,
    provider_transaction_id VARCHAR(100),
    provider_reference VARCHAR(120),
    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'VND',
    status VARCHAR(30) NOT NULL,
    failure_code VARCHAR(50),
    failure_message VARCHAR(500),
    expires_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_payment ON payment_transactions(payment_id);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_provider_ref ON payment_transactions(provider_reference);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_provider_tx ON payment_transactions(provider_transaction_id);

-- 3. Create refund_batches table
CREATE TABLE IF NOT EXISTS refund_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(60) NOT NULL UNIQUE,
    cinema_id BIGINT,
    showtime_id BIGINT,
    reason VARCHAR(255) NOT NULL,
    total_bookings INTEGER NOT NULL DEFAULT 0,
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    created_by BIGINT,
    approved_by BIGINT,
    completed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_refund_batches_showtime ON refund_batches(showtime_id);
CREATE INDEX IF NOT EXISTS idx_refund_batches_cinema ON refund_batches(cinema_id);

-- 4. Create refunds table
CREATE TABLE IF NOT EXISTS refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_code VARCHAR(60) NOT NULL UNIQUE,
    payment_id BIGINT REFERENCES payments(id) ON DELETE SET NULL,
    booking_id BIGINT,
    food_order_id BIGINT,
    user_id BIGINT NOT NULL,
    amount NUMERIC(12,2) NOT NULL,
    remaining_refundable_amount NUMERIC(12,2),
    reason VARCHAR(255) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    refund_batch_id BIGINT REFERENCES refund_batches(id) ON DELETE SET NULL,
    approved_by BIGINT,
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMP,
    completed_at TIMESTAMP,
    failure_reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_refunds_payment ON refunds(payment_id);
CREATE INDEX IF NOT EXISTS idx_refunds_booking ON refunds(booking_id);
CREATE INDEX IF NOT EXISTS idx_refunds_user ON refunds(user_id);
CREATE INDEX IF NOT EXISTS idx_refunds_batch ON refunds(refund_batch_id);

-- 5. Extend wallet_transactions table with ledger auditing fields
ALTER TABLE wallet_transactions ADD COLUMN IF NOT EXISTS balance_before NUMERIC(12,2);
ALTER TABLE wallet_transactions ADD COLUMN IF NOT EXISTS reference_type VARCHAR(50);
ALTER TABLE wallet_transactions ADD COLUMN IF NOT EXISTS reference_id BIGINT;
